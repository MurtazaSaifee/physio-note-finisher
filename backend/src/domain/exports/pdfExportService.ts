/**
 * PDF Export Service
 *
 * Generates structured SOAP PDFs directly with PDFKit. Clinical text is written
 * as text, never interpreted as HTML.
 */
import { Writable } from "node:stream";
import PDFDocument from "pdfkit";

export interface PdfExportHtmlInput {
  clinicName: string;
  patientName: string;
  date: string;
  visitType: string;
  subjective: string;
  objective: string;
  assessment: string;
  plan: string;
}

export function sanitizePdfText(text: string): string {
  // eslint-disable-next-line no-control-regex -- strips control characters on purpose
  return text.replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, "");
}

/**
 * Legacy compatibility for callers that still build an HTML string.
 * The returned document is intentionally plain-text-only.
 */
export function buildExportHtml(input: PdfExportHtmlInput): string {
  return [
    input.clinicName,
    "SOAP Note",
    `Patient: ${input.patientName}`,
    `Date: ${input.date}`,
    `Visit Type: ${input.visitType}`,
    "",
    "Subjective",
    input.subjective,
    "",
    "Objective",
    input.objective,
    "",
    "Assessment",
    input.assessment,
    "",
    "Plan",
    input.plan,
  ]
    .map(sanitizePdfText)
    .join("\n");
}

function collectPdf(doc: PDFKit.PDFDocument): Promise<Buffer> {
  const chunks: Buffer[] = [];
  const sink = new Writable({
    write(chunk: Buffer, _encoding, callback) {
      chunks.push(Buffer.from(chunk));
      callback();
    },
  });

  return new Promise((resolve, reject) => {
    sink.on("finish", () => resolve(Buffer.concat(chunks)));
    sink.on("error", reject);
    doc.on("error", reject);
    doc.pipe(sink);
  });
}

function writeLabelValue(doc: PDFKit.PDFDocument, label: string, value: string): void {
  doc.font("Helvetica-Bold").text(`${label}: `, { continued: true });
  doc.font("Helvetica").text(sanitizePdfText(value));
}

function writeSection(doc: PDFKit.PDFDocument, title: string, content: string): void {
  doc.moveDown(0.8);
  doc.font("Helvetica-Bold").fontSize(13).fillColor("#2563eb").text(title);
  doc
    .moveDown(0.25)
    .font("Helvetica")
    .fontSize(11)
    .fillColor("#1a1a1a")
    .text(sanitizePdfText(content) || " ", { lineGap: 3 });
}

export async function generateSoapPdfExport(
  input: PdfExportHtmlInput,
): Promise<Buffer> {
  const doc = new PDFDocument({
    size: "A4",
    margins: { top: 48, bottom: 48, left: 48, right: 48 },
    info: {
      Title: `SOAP Note - ${sanitizePdfText(input.clinicName)}`,
      Subject: "Clinical SOAP note",
      Creator: "Physio Note Finisher",
    },
  });
  const pdf = collectPdf(doc);

  doc
    .font("Helvetica-Bold")
    .fontSize(18)
    .fillColor("#2563eb")
    .text(sanitizePdfText(input.clinicName), { align: "center" });
  doc
    .font("Helvetica")
    .fontSize(11)
    .fillColor("#6b7280")
    .text("SOAP Note", { align: "center" });
  doc.moveDown();

  doc.fontSize(10).fillColor("#1a1a1a");
  writeLabelValue(doc, "Patient", input.patientName);
  writeLabelValue(doc, "Date", input.date);
  writeLabelValue(doc, "Visit Type", input.visitType);

  writeSection(doc, "Subjective", input.subjective);
  writeSection(doc, "Objective", input.objective);
  writeSection(doc, "Assessment", input.assessment);
  writeSection(doc, "Plan", input.plan);

  doc.moveDown(2);
  doc
    .font("Helvetica")
    .fontSize(8)
    .fillColor("#9ca3af")
    .text(
      "Generated by Physio Note Finisher - This document is a clinical record.",
      { align: "center" },
    );

  doc.end();
  return pdf;
}

export async function generatePdfExport(html: string): Promise<Buffer> {
  return generateSoapPdfExport({
    clinicName: "Physio Note Finisher",
    patientName: "",
    date: "",
    visitType: "",
    subjective: sanitizePdfText(html.replace(/<[^>]*>/g, " ")),
    objective: "",
    assessment: "",
    plan: "",
  });
}
